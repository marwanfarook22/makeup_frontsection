const englishTranslations = Object.fromEntries(
  Object.entries(arabicTranslations).map(([english, arabic]) => [
    arabic,
    english,
  ]),
);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    const savedLanguage = localStorage.getItem("sheglam-language");
    return savedLanguage === "ar" ? "ar" : "en";
  });

  useEffect(() => {
    localStorage.setItem("sheglam-language", language);
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
    document.title = "SheGlam | Beauty & Makeup";
  }, [language]);

  const value = useMemo(
    () => ({
      language,
      isArabic: language === "ar",
      setLanguage,
      t: (text) =>
        language === "ar"
          ? arabicTranslations[text] || text
          : englishTranslations[text] || text,
    }),
    [language],
  );

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}
